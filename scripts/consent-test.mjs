import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const script = readFileSync('src/components/Consent.astro', 'utf8').match(/<script is:inline>([\s\S]*?)<\/script>/)[1];
const banner = { hidden: true };
const current = {};
const status = {};
const buttons = ['granted', 'denied'].map(consent => ({ dataset: { consent }, events: {}, addEventListener(event, fn) { this.events[event] = fn; } }));
const loaded = [];
const context = { window: {}, localStorage: { getItem() { throw Error('blocked'); }, setItem() { throw Error('blocked'); } }, document: { querySelector: key => key === '[data-consent-banner]' ? banner : key === '[data-current-choice]' ? current : loaded[0], querySelectorAll: key => key === '[data-consent]' ? buttons : [status], createElement: () => ({ dataset: {} }), head: { appendChild: s => loaded.push(s) } } };
vm.runInNewContext(script, context);
assert.equal(context.window['ga-disable-G-HXM22WWPKP'], true);
assert.equal(loaded.length, 0);
assert.equal(banner.hidden, false);
buttons[0].events.click();
assert.equal(context.window['ga-disable-G-HXM22WWPKP'], false);
assert.equal(loaded.length, 1);
assert.match(status.textContent, /tidak dapat disimpan/);
buttons[1].events.click();
assert.equal(context.window['ga-disable-G-HXM22WWPKP'], true);
assert.equal(loaded.length, 1);
assert.match(status.textContent, /tidak dapat disimpan/);
console.log('Consent: blocked storage, explicit grant, refusal and truthful persistence status passed.');
